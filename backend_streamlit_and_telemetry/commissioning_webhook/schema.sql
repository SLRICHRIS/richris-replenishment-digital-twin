-- Additive physical telemetry storage. Existing model and review tables are unchanged.
CREATE TABLE IF NOT EXISTS public.amr_commissioning_samples (
	robot_id VARCHAR(16) NOT NULL,
	boot_id VARCHAR(64) NOT NULL,
	seq BIGINT NOT NULL,
	schema_version INTEGER NOT NULL,
	message_type VARCHAR(32) NOT NULL,
	received_at TIMESTAMP WITH TIME ZONE NOT NULL,
	stored_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
	client_id VARCHAR(64) NOT NULL,
	topic VARCHAR(128) NOT NULL,
	sample_time_s FLOAT NOT NULL,
	interval_s FLOAT NOT NULL,
	left_pulse_hz FLOAT NOT NULL,
	right_pulse_hz FLOAT NOT NULL,
	left_rpm FLOAT,
	right_rpm FLOAT,
	imu_sample_time_s FLOAT,
	accel_x_g FLOAT,
	accel_y_g FLOAT,
	accel_z_g FLOAT,
	gyro_x_dps FLOAT,
	gyro_y_dps FLOAT,
	gyro_z_dps FLOAT,
	gyro_z_rad_s FLOAT,
	gyro_bias_estimate_rad_s FLOAT,
	yaw_estimate_deg FLOAT,
	battery_sample_time_s FLOAT,
	battery_bus_voltage_v FLOAT,
	battery_shunt_voltage_mv FLOAT,
	battery_voltage_v FLOAT,
	battery_current_a FLOAT,
	battery_power_w FLOAT,
	device_soc_estimate_percent FLOAT,
	left_pulses_total BIGINT NOT NULL,
	right_pulses_total BIGINT NOT NULL,
	commanded_motion VARCHAR(16) NOT NULL,
	motor_output VARCHAR(16) NOT NULL,
	pwm_duty INTEGER NOT NULL,
	imu_who_am_i INTEGER NOT NULL,
	rpm_calibration_confirmed BOOLEAN NOT NULL,
	direction_measured BOOLEAN NOT NULL,
	gyro_available BOOLEAN NOT NULL,
	battery_available BOOLEAN NOT NULL,
	battery_continuity BOOLEAN NOT NULL,
	predictive_models_ready BOOLEAN NOT NULL,
	payload_sha256 VARCHAR(64) NOT NULL,
	payload JSONB NOT NULL,
	quality_notes JSONB NOT NULL,
	PRIMARY KEY (robot_id, boot_id, seq),
  CONSTRAINT ck_amr_commissioning_0 CHECK (robot_id = 'amr01'),
  CONSTRAINT ck_amr_commissioning_1 CHECK (schema_version = 1),
  CONSTRAINT ck_amr_commissioning_2 CHECK (message_type = 'mh_ir_commissioning'),
  CONSTRAINT ck_amr_commissioning_3 CHECK (topic = 'robot/amr01/commissioning'),
  CONSTRAINT ck_amr_commissioning_4 CHECK (boot_id ~ '^[0-9a-f]{16}$'),
  CONSTRAINT ck_amr_commissioning_5 CHECK (client_id = 'amr01-ir-' || boot_id),
  CONSTRAINT ck_amr_commissioning_6 CHECK (seq BETWEEN 0 AND 4294967295),
  CONSTRAINT ck_amr_commissioning_7 CHECK (left_pulses_total BETWEEN 0 AND 9007199254740991),
  CONSTRAINT ck_amr_commissioning_8 CHECK (right_pulses_total BETWEEN 0 AND 9007199254740991),
  CONSTRAINT ck_amr_commissioning_9 CHECK (sample_time_s >= 0 AND interval_s > 0),
  CONSTRAINT ck_amr_commissioning_10 CHECK (left_pulse_hz >= 0 AND right_pulse_hz >= 0),
  CONSTRAINT ck_amr_commissioning_11 CHECK (pwm_duty BETWEEN 0 AND 255),
  CONSTRAINT ck_amr_commissioning_12 CHECK (imu_who_am_i BETWEEN 0 AND 255),
  CONSTRAINT ck_amr_commissioning_13 CHECK (NOT direction_measured AND NOT predictive_models_ready),
  CONSTRAINT ck_amr_commissioning_14 CHECK (commanded_motion IN ('stopped','forward','backward','left','right')),
  CONSTRAINT ck_amr_commissioning_15 CHECK (motor_output IN ('stopped','forward','backward','left','right')),
  CONSTRAINT ck_amr_commissioning_16 CHECK (device_soc_estimate_percent IS NULL OR device_soc_estimate_percent BETWEEN 0 AND 100),
  CONSTRAINT ck_amr_commissioning_17 CHECK (payload_sha256 ~ '^[0-9a-f]{64}$'),
  CONSTRAINT ck_amr_commissioning_18 CHECK (jsonb_typeof(payload) = 'object' AND jsonb_typeof(quality_notes) = 'array'),
  CONSTRAINT ck_amr_commissioning_19 CHECK (payload->>'robot_id' = robot_id AND payload->>'boot_id' = boot_id),
  CONSTRAINT ck_amr_commissioning_20 CHECK ((rpm_calibration_confirmed AND left_rpm >= 0 AND right_rpm >= 0) OR (NOT rpm_calibration_confirmed AND left_rpm IS NULL AND right_rpm IS NULL)),
  CONSTRAINT ck_amr_commissioning_21 CHECK (sample_time_s IS NULL OR (sample_time_s > '-Infinity'::float8 AND sample_time_s < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_22 CHECK (interval_s IS NULL OR (interval_s > '-Infinity'::float8 AND interval_s < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_23 CHECK (left_pulse_hz IS NULL OR (left_pulse_hz > '-Infinity'::float8 AND left_pulse_hz < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_24 CHECK (right_pulse_hz IS NULL OR (right_pulse_hz > '-Infinity'::float8 AND right_pulse_hz < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_25 CHECK (left_rpm IS NULL OR (left_rpm > '-Infinity'::float8 AND left_rpm < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_26 CHECK (right_rpm IS NULL OR (right_rpm > '-Infinity'::float8 AND right_rpm < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_27 CHECK (imu_sample_time_s IS NULL OR (imu_sample_time_s > '-Infinity'::float8 AND imu_sample_time_s < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_28 CHECK (accel_x_g IS NULL OR (accel_x_g > '-Infinity'::float8 AND accel_x_g < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_29 CHECK (accel_y_g IS NULL OR (accel_y_g > '-Infinity'::float8 AND accel_y_g < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_30 CHECK (accel_z_g IS NULL OR (accel_z_g > '-Infinity'::float8 AND accel_z_g < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_31 CHECK (gyro_x_dps IS NULL OR (gyro_x_dps > '-Infinity'::float8 AND gyro_x_dps < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_32 CHECK (gyro_y_dps IS NULL OR (gyro_y_dps > '-Infinity'::float8 AND gyro_y_dps < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_33 CHECK (gyro_z_dps IS NULL OR (gyro_z_dps > '-Infinity'::float8 AND gyro_z_dps < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_34 CHECK (gyro_z_rad_s IS NULL OR (gyro_z_rad_s > '-Infinity'::float8 AND gyro_z_rad_s < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_35 CHECK (gyro_bias_estimate_rad_s IS NULL OR (gyro_bias_estimate_rad_s > '-Infinity'::float8 AND gyro_bias_estimate_rad_s < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_36 CHECK (yaw_estimate_deg IS NULL OR (yaw_estimate_deg > '-Infinity'::float8 AND yaw_estimate_deg < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_37 CHECK (battery_sample_time_s IS NULL OR (battery_sample_time_s > '-Infinity'::float8 AND battery_sample_time_s < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_38 CHECK (battery_bus_voltage_v IS NULL OR (battery_bus_voltage_v > '-Infinity'::float8 AND battery_bus_voltage_v < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_39 CHECK (battery_shunt_voltage_mv IS NULL OR (battery_shunt_voltage_mv > '-Infinity'::float8 AND battery_shunt_voltage_mv < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_40 CHECK (battery_voltage_v IS NULL OR (battery_voltage_v > '-Infinity'::float8 AND battery_voltage_v < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_41 CHECK (battery_current_a IS NULL OR (battery_current_a > '-Infinity'::float8 AND battery_current_a < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_42 CHECK (battery_power_w IS NULL OR (battery_power_w > '-Infinity'::float8 AND battery_power_w < 'Infinity'::float8)),
  CONSTRAINT ck_amr_commissioning_43 CHECK (device_soc_estimate_percent IS NULL OR (device_soc_estimate_percent > '-Infinity'::float8 AND device_soc_estimate_percent < 'Infinity'::float8))
);
CREATE INDEX IF NOT EXISTS ix_amr_commissioning_received ON public.amr_commissioning_samples (robot_id, received_at DESC, boot_id DESC, seq DESC);
GRANT SELECT, INSERT ON TABLE public.amr_commissioning_samples TO amr_worker;
GRANT SELECT ON TABLE public.amr_commissioning_samples TO amr_reader;
